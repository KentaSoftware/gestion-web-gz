    view.unmount()
    render(<ClientsPage />)
    fireEvent.click(await screen.findByRole('button', { name: 'Retomar creación pendiente' }))
    expect(screen.getByLabelText('Nombre *')).toHaveValue('Nuevo')
    expect(screen.getByRole('button', { name: 'Cerrar recuperación' })).toBeDisabled()
