    expect(form).not.toBeNull()
    if (form) fireEvent.submit(form)
    expect(mode === 'create' ? mocks.create : mocks.update).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByRole('button', { name: 'Seleccionar punto de prueba' }))
